# 1. Resolve Evidence Directory
$tempExtractDir = $null
if (-not $EvidencePath) {
    # Search locations in priority order: current folder, parent folder, script root, script parent
    $currentLoc = (Get-Location).Path
    $parentLoc = if ($currentLoc) { Split-Path $currentLoc -Parent } else { $null }
    $scriptLoc = $PSScriptRoot
    $scriptParentLoc = if ($PSScriptRoot) { Split-Path $PSScriptRoot -Parent } else { $null }

    $searchLocations = @($currentLoc, $parentLoc, $scriptLoc, $scriptParentLoc) | 
        Where-Object { $_ -and (Test-Path $_) } | Select-Object -Unique

    foreach ($loc in $searchLocations) {
        $latestDir = Get-ChildItem -Path $loc -Directory -Filter "DFIR-*" -ErrorAction SilentlyContinue | 
            Sort-Object LastWriteTime -Descending | Select-Object -First 1

        if ($latestDir) {
            $EvidencePath = $latestDir.FullName
            Write-Host "[+] Auto-detected evidence directory: $EvidencePath" -ForegroundColor Green
            break
        }

        $latestZip = Get-ChildItem -Path $loc -File -Filter "DFIR-*.zip" -ErrorAction SilentlyContinue | 
            Sort-Object LastWriteTime -Descending | Select-Object -First 1

        if ($latestZip) {
            $EvidencePath = $latestZip.FullName
            Write-Host "[+] Auto-detected evidence archive: $EvidencePath" -ForegroundColor Green
            break
        }
    }
}

if (-not $EvidencePath -or -not (Test-Path $EvidencePath)) {
    Write-Error "No evidence directory (DFIR-*) or archive (DFIR-*.zip) found in the current or parent directory. Please specify -EvidencePath <path>"
    return
}

