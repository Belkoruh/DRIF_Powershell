# Helper function to read and convert CSV safely
function Import-SafeCsv {
    param([string]$Path)
    if (Test-Path $Path) {
        try {
            $data = Import-Csv -Path $Path -ErrorAction Stop
            return @($data)
        } catch {
            Write-Warning "Could not parse CSV: $Path ($($_.Exception.Message))"
            return @()
        }
    }
    return @()
}

# Helper to escape HTML characters
function Escape-Html {
    param([string]$Text)
    if ([string]::IsNullOrEmpty($Text)) { return "" }
    return [System.Web.HttpUtility]::HtmlEncode($Text)
}

