.SYNOPSIS
    Generates an interactive, standalone HTML Forensic Report from DFIR collected artifacts.

.DESCRIPTION
    Parses collected CSV files and forensic evidence generated by DFIR-Script.ps1 and granular
    acquisition scripts, generating a standalone, interactive HTML dashboard. Includes metric cards,
    real-time search/filter, sorting, categorized tabs, and automated suspicious indicator highlighting.

.PARAMETER EvidencePath
    The path to the DFIR output directory (e.g. .\DFIR-HOSTNAME-2026-08-21) or evidence ZIP file.
    If omitted, the script automatically searches for the most recent DFIR-* folder in the current directory.

.PARAMETER OutputFile
    Path for the generated HTML report. Defaults to 'DFIR-Report-<Hostname>-<Timestamp>.html'.

.PARAMETER OpenReport
    Automatically opens the generated HTML report in the default web browser upon completion.

.PARAMETER Title
    Custom title for the forensic report.

.EXAMPLE
    .\Generate-DFIRHtmlReport.ps1

.EXAMPLE
    .\Generate-DFIRHtmlReport.ps1 -EvidencePath ".\DFIR-DESKTOP-2026-08-21" -OpenReport

.EXAMPLE
    .\Generate-DFIRHtmlReport.ps1 -EvidencePath ".\DFIR-DESKTOP-2026-08-21.zip" -OutputFile "C:\Reports\Incident-001.html" -OpenReport
#>

