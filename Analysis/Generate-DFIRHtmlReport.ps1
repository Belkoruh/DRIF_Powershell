    Write-Host "[*] Extracting ZIP archive to temporary location..." -ForegroundColor Yellow
    $tempExtractDir = Join-Path $env:TEMP "DFIR_Extract_$(Get-Random)"
    New-Item -Path $tempExtractDir -ItemType Directory -Force | Out-Null
    Expand-Archive -Path $EvidencePath -DestinationPath $tempExtractDir -Force
